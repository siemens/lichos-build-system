"""Listener protocol for real-time scheduler progress reporting."""

from typing import Protocol, runtime_checkable


@runtime_checkable
class SchedulerListener(Protocol):
    """Callback protocol for real-time scheduler progress reporting."""

    def on_build_triggered(self, package: str, pipeline_url: str) -> None: ...
    def on_build_succeeded(self, package: str, pipeline_url: str) -> None: ...
    def on_build_failed(self, package: str, reason: str) -> None: ...
    def on_trigger_failed(self, package: str) -> None: ...
    def on_polling_start(self, packages: list[str]) -> None: ...
    def on_polling_update(self, still_building: list[str]) -> None: ...
    def on_waiting_for_pipelines(self, packages: list[str]) -> None: ...
    def on_blocked(self, packages: list[str]) -> None: ...
